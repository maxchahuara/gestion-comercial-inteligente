// Secret fields survive a rotation in memory, never in saved-instance state or an export.
class CopyDialogState:ViewModel() {
    var password by mutableStateOf("")
    var confirmation by mutableStateOf("")
    var busy by mutableStateOf(false)
    var error by mutableStateOf("")
    var generated by mutableStateOf<File?>(null)
    var restored by mutableStateOf<Campaign?>(null)
    fun clear(){password="";confirmation="";error="";generated=null;restored=null}
    fun export(g:AppGraph,id:String) {
        error=when {password.length<10->"Usa una contraseña de al menos 10 caracteres.";password!=confirmation->"Las contraseñas no coinciden.";else->""}
        if(error.isNotBlank() || busy)return
        busy=true;val pass=password.toCharArray()
        viewModelScope.launch {
            try { generated=g.assets.backup(id,pass) } catch(e:Exception){error=safeError(e)}
            finally {pass.fill('\u0000');busy=false}
        }
    }
    fun restore(g:AppGraph,uri:Uri) {
        if(password.length<10){error="Escribe la contraseña de la copia: al menos 10 caracteres.";return}
        if(busy)return
        busy=true;error="";val pass=password.toCharArray()
        viewModelScope.launch {
            try { restored=g.assets.restore(uri,pass) } catch(e:Exception){error=safeError(e)}
            finally {pass.fill('\u0000');busy=false}
        }
    }
    override fun onCleared(){clear();super.onCleared()}
}

@Composable internal fun ExportCopyDialog(g:AppGraph,campaign:Campaign,onDismiss:()->Unit,onGenerated:(File)->Unit) {
    val state:CopyDialogState=viewModel(key="export-copy-"+campaign.id)
    LaunchedEffect(state.generated){state.generated?.let { onGenerated(it);state.clear() }}
    fun close(){if(!state.busy){state.clear();onDismiss()}}
    AlertDialog(onDismissRequest=::close,modifier=Modifier.imePadding(),properties=DialogProperties(decorFitsSystemWindows=false),title={Text("Exportar copia")},text={
        Column(Modifier.verticalScroll(rememberScrollState()),verticalArrangement=Arrangement.spacedBy(14.dp)) {
            Text(campaign.name,style=MaterialTheme.typography.titleSmall)
            Text("Incluye los datos y archivos de esta campaña. No incluye tu cuenta de ChatGPT.")
            SecretField("Contraseña",state.password,{state.password=it;state.error=""},!state.busy,"Mínimo 10 caracteres.")
            SecretField("Repite la contraseña",state.confirmation,{state.confirmation=it;state.error=""},!state.busy)
            Text("Necesitarás esta contraseña para restaurar la copia. Elegirás dónde guardarla en Android.",style=MaterialTheme.typography.bodySmall)
            if(state.error.isNotBlank())Text(state.error,color=MaterialTheme.colorScheme.error)
            if(state.busy){LinearProgressIndicator(Modifier.fillMaxWidth());Text("Creando copia protegida…")}
        }
    },confirmButton={CampTextButton(onClick={state.export(g,campaign.id)},enabled=!state.busy){Text(if(state.busy)"Creando…" else "Guardar copia")}},dismissButton={CampTextButton(onClick=::close,enabled=!state.busy){Text("Cancelar")}})
}

@Composable internal fun RestoreCopyDialog(g:AppGraph,uri:Uri,onDismiss:()->Unit,onChangeFile:()->Unit,onRestored:(Campaign)->Unit) {
    val state:CopyDialogState=viewModel(key="restore-copy-"+uri.toString().hashCode())
    val name by produceState("Copia seleccionada",uri){value=withContext(Dispatchers.IO){runCatching{g.context.contentResolver.query(uri,arrayOf(OpenableColumns.DISPLAY_NAME),null,null,null)?.use { if(it.moveToFirst())it.getString(0).take(200) else null }}.getOrNull() ?: "Copia seleccionada"}}
    LaunchedEffect(state.restored){state.restored?.let { onRestored(it);state.clear() }}
    fun close(){if(!state.busy){state.clear();onDismiss()}}
    AlertDialog(onDismissRequest=::close,modifier=Modifier.imePadding(),properties=DialogProperties(decorFitsSystemWindows=false),title={Text("Restaurar copia")},text={
        Column(Modifier.verticalScroll(rememberScrollState()),verticalArrangement=Arrangement.spacedBy(14.dp)) {
            Text("Archivo seleccionado",style=MaterialTheme.typography.labelLarge);Text(name)
            CampTextButton(onClick={state.clear();onChangeFile()},enabled=!state.busy){Text("Cambiar archivo")}
            Text("Se creará una campaña nueva en modo borradores. Las campañas actuales se conservan.")
            Text("Sus tareas no se ejecutarán automáticamente. La cuenta de ChatGPT no forma parte de la copia.",style=MaterialTheme.typography.bodySmall)
            SecretField("Contraseña de la copia",state.password,{state.password=it;state.error=""},!state.busy)
            if(state.error.isNotBlank())Text(state.error,color=MaterialTheme.colorScheme.error)
            if(state.busy){LinearProgressIndicator(Modifier.fillMaxWidth());Text("Restaurando campaña…")}
        }
    },confirmButton={CampTextButton(onClick={state.restore(g,uri)},enabled=!state.busy){Text(if(state.busy)"Restaurando…" else "Restaurar")}},dismissButton={CampTextButton(onClick=::close,enabled=!state.busy){Text("Cancelar")}})
}

@Composable private fun SecretField(label:String,value:String,onChange:(String)->Unit,enabled:Boolean,help:String="") {
    var visible by remember{mutableStateOf(false)}
    val focus=LocalFocusManager.current;val keyboard=LocalSoftwareKeyboardController.current
    CampTextField(value,{onChange(it.take(200))},Modifier.fillMaxWidth(),label={Text(label,maxLines=1,overflow=androidx.compose.ui.text.style.TextOverflow.Ellipsis)},singleLine=true,enabled=enabled,
        keyboardOptions=KeyboardOptions(keyboardType=KeyboardType.Password,autoCorrectEnabled=false,imeAction=ImeAction.Done),
        keyboardActions=KeyboardActions(onDone={focus.clearFocus();keyboard?.hide()}),
        visualTransformation=if(visible)VisualTransformation.None else PasswordVisualTransformation(),
        trailingIcon={IconButton(onClick={visible=!visible},enabled=enabled){Icon(if(visible)Icons.Outlined.VisibilityOff else Icons.Outlined.Visibility,if(visible)"Ocultar contraseña" else "Mostrar contraseña")}},
        supportingText=if(help.isNotBlank()){{Text(help)}}else null)
}
